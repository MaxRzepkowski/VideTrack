<?php

namespace App\Http\Controllers\Auth;

use App\Actions\Users\RecoverAccount;
use App\Http\Controllers\Controller;
use App\Http\Requests\Auth\ResetPasswordRequest;
use App\Models\User;
use Illuminate\Auth\Events\PasswordReset;
use Illuminate\Http\RedirectResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Password;
use Illuminate\Validation\ValidationException;
use Inertia\Inertia;
use Inertia\Response;

class NewPasswordController extends Controller
{
    /**
     * Show the password reset page.
     */
    public function create(Request $request): Response
    {
        return Inertia::render('auth/ResetPassword', [
            'email' => $request->email,
            'token' => $request->route('token'),
        ]);
    }

    /**
     * Handle an incoming new password request.
     *
     * @throws ValidationException
     */
    public function store(ResetPasswordRequest $request, RecoverAccount $recover): RedirectResponse
    {
        $credentials = $request->credentials();

        // Broker validates the token, then runs the callback to persist the new password.
        /** @var string $status the broker answers with a translation key */
        $status = Password::reset(
            $credentials,
            function (User $user, string $password) use ($recover): void {
                $recover->execute($user, $password);

                event(new PasswordReset($user));
            }
        );

        if ($status == Password::PasswordReset) {
            return to_route('login')->with('status', __($status));
        }

        throw ValidationException::withMessages([
            'email' => [__($status)],
        ]);
    }
}
